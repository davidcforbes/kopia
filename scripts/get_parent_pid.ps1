# get_parent_pid.ps1 -- print our caller's PID. The wrapper invokes this from
# cmd via `for /f` to capture its own (cmd batch) PID so the heartbeat
# watchdog can identify the wrapper's kopia.exe children by ParentProcessId.
#
# Output: a single integer PID on stdout, nothing else. Empty stdout (no
# integer) signals failure to the caller's `if not defined`.
#
# Why P/Invoke NtQueryInformationProcess instead of WMI/CIM:
# Both Get-WmiObject and Get-CimInstance route through DCOM by default. Under
# S4U-elevated scheduled-task context on this host, DCOM access is restricted
# enough that Win32_Process queries return empty (kopia-i1p reopened). The
# 2026-05-06 nightly logged 'WARNING: could not resolve wrapper PID; stall
# guard not started' even with the previous Get-WmiObject implementation.
#
# NtQueryInformationProcess is a pure user-mode syscall against the calling
# process's own token. No DCOM, no WMI service, no DCE/RPC -- just ntdll.
# Works under any token context including S4U.

[CmdletBinding()] param()

$ErrorActionPreference = 'SilentlyContinue'

Add-Type -ErrorAction Stop -TypeDefinition @"
using System;
using System.Diagnostics;
using System.Runtime.InteropServices;

public class _ParentPid {
    [StructLayout(LayoutKind.Sequential)]
    private struct PROCESS_BASIC_INFORMATION {
        public IntPtr Reserved1;
        public IntPtr PebBaseAddress;
        public IntPtr Reserved2_0;
        public IntPtr Reserved2_1;
        public IntPtr UniqueProcessId;
        public IntPtr InheritedFromUniqueProcessId;
    }

    [DllImport("ntdll.dll")]
    private static extern int NtQueryInformationProcess(
        IntPtr hProcess, int pic, ref PROCESS_BASIC_INFORMATION pbi,
        int cb, out int pSize);

    public static int Get() {
        var p = Process.GetCurrentProcess();
        var pbi = new PROCESS_BASIC_INFORMATION();
        int returnLength;
        int status = NtQueryInformationProcess(p.Handle, 0, ref pbi,
            Marshal.SizeOf(pbi), out returnLength);
        if (status != 0) { return -1; }
        return pbi.InheritedFromUniqueProcessId.ToInt32();
    }
}
"@

$ppid = [_ParentPid]::Get()
if ($ppid -gt 0) { Write-Output $ppid }

