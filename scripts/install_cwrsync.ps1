# install_cwrsync.ps1 — Idempotent installer for cwRsync client (Itefix).
#
# Pinned to v6.4.8 by SHA256. Downloads the official zip from the
# itefixnet/cwrsync-client GitHub release, verifies hash, extracts into
# C:\cwrsync\, and locks ACLs to SYSTEM:F Administrators:F david:R so the
# unprivileged user can't tamper with the binary the scheduled task runs.
#
# Background: cwRsync provides a native Windows rsync.exe linked against
# cygwin1.dll. It reads VSS shadow junctions (\\?\GLOBALROOT\Device\...)
# natively, runs in the elevated context of the scheduled task, and
# delivers block-level delta-copy semantics that file-level robocopy
# cannot. Replaces the robocopy /MIR call in daily_d_replica.ps1.
#
# License: BSD-2-Clause. Source-buildable from samba.org rsync 3.4.1 +
# three documented patches (transliterate, ignore-case,
# no-password-file-check) — see itefixnet/cwrsync-client/build/template.sh.
#
# Run once manually elevated before daily_d_replica.ps1 first uses rsync.

[CmdletBinding()]
param(
    [string]$InstallRoot = 'C:\cwrsync',
    [string]$Version     = '6.4.8',
    [string]$ExpectedSha256 = '8798363513b05c355ad87f8f3efbb15b7b6433996b652efec712efd52d7c8336',
    [string]$DownloadUrl = 'https://github.com/itefixnet/cwrsync-client/releases/download/v6.4.8/cwrsync_6.4.8_x64_free.zip',
    [string]$LocalUser   = 'ChrisLaptop2\david'
)

$ErrorActionPreference = 'Stop'

function Write-Step { param([string]$Msg) Write-Host "[install_cwrsync] $Msg" }

# ---- Elevation check ----
$elevated = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $elevated) { throw 'must run elevated (need to write C:\cwrsync\ and set restrictive ACLs)' }

# ---- Idempotency: skip if already installed at expected sha256 ----
$rsyncExe = Join-Path $InstallRoot 'bin\rsync.exe'
$stampFile = Join-Path $InstallRoot ".cwrsync-$Version.installed"
if ((Test-Path -LiteralPath $rsyncExe) -and (Test-Path -LiteralPath $stampFile)) {
    $stamped = (Get-Content -LiteralPath $stampFile -Raw).Trim()
    if ($stamped -eq $ExpectedSha256) {
        Write-Step "already installed at $InstallRoot (sha256 match) — nothing to do"
        & $rsyncExe --version | Select-Object -First 1
        exit 0
    }
    Write-Step "existing install does not match expected sha256 — reinstalling"
}

# ---- Download to temp ----
$tmpZip = Join-Path $env:TEMP "cwrsync_${Version}_x64_free.zip"
if (Test-Path -LiteralPath $tmpZip) { Remove-Item -LiteralPath $tmpZip -Force }
Write-Step "downloading $DownloadUrl"
Invoke-WebRequest -Uri $DownloadUrl -OutFile $tmpZip -UseBasicParsing

# ---- Verify SHA256 ----
$actual = (Get-FileHash -Path $tmpZip -Algorithm SHA256).Hash.ToLower()
if ($actual -ne $ExpectedSha256.ToLower()) {
    Remove-Item -LiteralPath $tmpZip -Force
    throw "sha256 mismatch: expected $ExpectedSha256, got $actual"
}
Write-Step "sha256 verified ($actual)"

# ---- Extract ----
if (Test-Path -LiteralPath $InstallRoot) {
    Write-Step "removing prior $InstallRoot"
    Remove-Item -LiteralPath $InstallRoot -Recurse -Force
}
New-Item -ItemType Directory -Path $InstallRoot -Force | Out-Null
Write-Step "extracting to $InstallRoot"
Expand-Archive -LiteralPath $tmpZip -DestinationPath $InstallRoot -Force
Remove-Item -LiteralPath $tmpZip -Force

if (-not (Test-Path -LiteralPath $rsyncExe)) { throw "extract did not produce $rsyncExe" }

# ---- Lock ACLs (SYSTEM:F, Administrators:F, $LocalUser:R) ----
Write-Step "locking ACLs"
& icacls.exe $InstallRoot /inheritance:r | Out-Null
& icacls.exe $InstallRoot /grant:r `
    'SYSTEM:(OI)(CI)F' `
    'Administrators:(OI)(CI)F' `
    "${LocalUser}:(OI)(CI)R" | Out-Null
& icacls.exe $InstallRoot /remove 'Authenticated Users' 'Users' 2>&1 | Out-Null

# ---- Stamp & smoke test ----
Set-Content -LiteralPath $stampFile -Value $ExpectedSha256 -Force
Write-Step 'smoke test:'
& $rsyncExe --version | Select-Object -First 3

Write-Step "installed cwRsync $Version at $InstallRoot"

